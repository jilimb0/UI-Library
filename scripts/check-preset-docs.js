#!/usr/bin/env node

const fs = require('node:fs');
const path = require('node:path');

const root = path.join(__dirname, '..');
const presetsPath = path.join(root, 'registry', 'source', 'presets.json');

function fail(message) {
  console.error(`[preset-check] ${message}`);
  process.exit(1);
}

if (!fs.existsSync(presetsPath)) {
  fail('Missing registry/source/presets.json');
}

const registry = JSON.parse(fs.readFileSync(presetsPath, 'utf8'));
const presetNames = ['enterprise', 'saas', 'marketing'];

function buildDoc(name, preset) {
  const lines = [];
  lines.push('# Generated by scripts/bootstrap-preset.js');
  lines.push(`preset: ${name}`);
  lines.push(`description: ${preset.description}`);
  lines.push('');
  lines.push('## Dependencies');
  for (const dep of preset.dependencies) {
    lines.push(`- ${dep}`);
  }
  lines.push('');
  lines.push('## Features');
  for (const feature of preset.features) {
    lines.push(`- ${feature}`);
  }
  lines.push('');
  lines.push('## Install');
  lines.push(`pnpm add ${preset.dependencies.join(' ')}`);
  return `${lines.join('\n')}\n`;
}

for (const name of presetNames) {
  const preset = registry.presets?.[name];
  if (!preset) {
    fail(`Missing preset "${name}" in registry/source/presets.json`);
  }

  const expected = buildDoc(name, preset);
  const filePath = path.join(root, 'docs', 'guides', `preset-${name}.md`);

  if (!fs.existsSync(filePath)) {
    fail(`Missing generated file docs/guides/preset-${name}.md`);
  }

  const actual = fs.readFileSync(filePath, 'utf8');
  if (actual !== expected) {
    fail(
      `docs/guides/preset-${name}.md is out of sync. Run: pnpm preset:bootstrap ${name}`
    );
  }
}

console.log('[preset-check] PASS: preset docs are in sync with registry.');
